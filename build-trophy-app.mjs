import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const stripExports = source => source.replace(/^export\s+/gm, '');

const intake = stripExports(read('trophy-intake.js'));
const gallery = stripExports(read('trophy-gallery.js'));
const usage = stripExports(read('trophy-usage.js'));
const trophySource = read('trophy.js');
const trophy = trophySource.replace(/^import\s+.*;\s*$/gm, '');

if (trophy === trophySource || /^\s*import\s/m.test(trophy)) {
  throw new Error('Trophy Studio imports changed; update the bundle builder before generating the production script.');
}
for (const [name, source] of Object.entries({ intake, gallery, usage })) {
  if (/^\s*export\s/m.test(source)) throw new Error(`Could not remove module exports from ${name}.`);
}

const bundle = `/* Generated by scripts/build-trophy-app.mjs. Do not edit by hand. */\n(function () {\n'use strict';\n\n${intake}\n\n${gallery}\n\n${usage}\n\n${trophy}\n})();\n`;
fs.writeFileSync(path.join(root, 'trophy-app.js'), bundle);
console.log(`Built trophy-app.js (${Buffer.byteLength(bundle)} bytes) without runtime module imports.`);
